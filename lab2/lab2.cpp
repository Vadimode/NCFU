#include <iostream>
#include <cmath>    // Библиотека для функций sqrt() и abs()
#include <iomanip>  // Библиотека для управления точностью вывода (setprecision)

int main() {
    // Настройка шрифтов для корректного отображения русского языка в консоли
    setlocale(LC_ALL, "ru");

    // =========================================================================
    // === ЗАДАНИЕ 1. БАЗОВЫЙ УРОВЕНЬ ===
    // Условие: Вычислить периметр прямоугольника со сторонами a и b
    // =========================================================================
    std::cout << "==================================================\n";
    std::cout << "1. БАЗОВЫЙ УРОВЕНЬ: Периметр прямоугольника\n";
    std::cout << "==================================================\n";

    double sideA = 0.0;
    double sideB = 0.0;

    std::cout << "Введите длину стороны A: ";
    std::cin >> sideA;
    std::cout << "Введите длину стороны B: ";
    std::cin >> sideB;

    // Вычисление периметра. Используем 2.0, чтобы избежать неявного приведения
    double perimeter = 2.0 * (sideA + sideB);
    std::cout << "-> Результат: Периметр прямоугольника = " << perimeter << "\n\n";


    // =========================================================================
    // === ЗАДАНИЕ 2. СРЕДНИЙ УРОВЕНЬ ===
    // Условие: Вычислить среднее арифметическое и среднее геометрическое двух чисел
    // =========================================================================
    std::cout << "==================================================\n";
    std::cout << "2. СРЕДНИЙ УРОВЕНЬ: Среднее арифметическое и геометрическое\n";
    std::cout << "==================================================\n";

    int number1 = 0;
    int number2 = 0;

    std::cout << "Введите первое целое число: ";
    std::cin >> number1;
    std::cout << "Введите второе целое число: ";
    std::cin >> number2;

    // Защита: среднее геометрическое извлекается только из неотрицательного произведения
    if (number1 * number2 < 0) {
        std::cout << "-> Ошибка: Произведение чисел отрицательное, корень извлечь нельзя!\n\n";
    }
    else {
        // Явное приведение типов static_cast для исключения целочисленного деления
        double averageArithmetic = static_cast<double>(number1 + number2) / 2.0;
        double averageGeometric = std::sqrt(static_cast<double>(number1 * number2));

        // Настройка вывода (2 знака после запятой)
        std::cout << std::fixed << std::setprecision(2);
        std::cout << "-> Результат:\n";
        std::cout << "   Среднее арифметическое = " << averageArithmetic << "\n";
        std::cout << "   Среднее геометрическое = " << averageGeometric << "\n\n";
    }


    // =========================================================================
    // === ЗАДАНИЕ 3. ПОВЫШЕННЫЙ УРОВЕНЬ ===
    // Условие: Найти сумму и произведение цифр трехзначного числа
    // =========================================================================
    std::cout << "==================================================\n";
    std::cout << "3. ПОВЫШЕННЫЙ УРОВЕНЬ: Анализ трехзначного числа\n";
    std::cout << "==================================================\n";

    int inputNumber = 0;
    std::cout << "Введите трехзначное целое число: ";
    std::cin >> inputNumber;

    // Проверка на корректность ввода (если пользователь ввел буквы вместо цифр)
    if (std::cin.fail()) {
        std::cout << "-> Ошибка: Введены некорректные данные (не число)!\n";
        std::cin.clear();
        std::cin.ignore(10000, '\n');
        return 1;
    }

    // Избавляемся от минуса, если число ввели отрицательное
    int number = std::abs(inputNumber);

    // Проверка строгого условия: число должно быть трехзначным
    if (number < 100 || number > 999) {
        std::cout << "-> Ошибка: Число не является трехзначным!\n";
        return 1;
    }

    // Извлечение цифр числа с помощью явного приведения типов static_cast
    int digit1 = static_cast<int>(number / 100);       // Первая цифра (сотни)
    int digit2 = static_cast<int>((number / 10) % 10); // Вторая цифра (десятки)
    int digit3 = static_cast<int>(number % 10);        // Третья цифра (единицы)

    int digitSum = digit1 + digit2 + digit3;
    int digitProduct = digit1 * digit2 * digit3;

    std::cout << "-> Результат:\n";
    std::cout << "   Цифры числа: " << digit1 << ", " << digit2 << ", " << digit3 << "\n";
    std::cout << "   Сумма цифр = " << digitSum << "\n";
    std::cout << "   Произведение цифр = " << digitProduct << "\n";
    std::cout << "==================================================\n";

    return 0; // Успешное окончание всей лабораторной работы
}

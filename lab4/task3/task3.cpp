#include <iostream>
#include <limits> //  для очистки буфера ввода при ошибке
using namespace std;
int main() {
    setlocale(LC_ALL, "Russian");
    int score; // Переменная для введенного балла
    cout << " Система оценок ECTS " << endl;
    cout << "Введите количество баллов (от 0 до 100): ";
    cin >> score;
    //Проверка на ввод букв или символов вместо числа
    if (cin.fail()) {
        cout << "Ошибка: нужно ввести целое число, а не текст!" << endl;
        cin.clear(); // Сбрасываеn ошибки потока ввода
        cin.ignore(numeric_limits<streamsize>::max(), '\n'); // Очищаеn буфер до конца строки
        return 1;
    }
    //Попадает ли число в допустимый диапазон от 0 до 100
    if (score < 0 || score > 100) {
        cout << "Ошибка: балл должен быть в диапазоне от 0 до 100!" << endl;
        return 1;
    }
    // Передаем в switch количество десятков (целочисленное деление на 10)
    switch (score / 10) {
    case 10: // 100 баллов
    case 9:  // 90–99 баллов
        cout << "Оценка: A — Отлично " << endl;
        break;
    case 8:  // 80–89 баллов 
        if (score >= 82) {
            cout << "Оценка: B — Очень хорошо " << endl;
        }
        else {
            // Если 80 или 81 балл — это уже оценка C
            cout << "Оценка: C — Хорошо " << endl;
        }
        break;
    case 7:  // 70–79 баллов (относится к оценке C: 74–81)
        if (score >= 74) {
            cout << "Оценка: C — Хорошо " << endl;
        }
        else {
            // Если 70–73 балла — это оценка D
            cout << "Оценка: D — Удовлетворительно " << endl;
        }
        break;
    case 6:  // 60–69 баллов (оценка D: 64–73, оценка E: 60–63)
        if (score >= 64) {
            cout << "Оценка: D — Удовлетворительно " << endl;
        }
        else {
            cout << "Оценка: E — Достаточно " << endl;
        }
        break;
    case 5:  // 50–59 баллов
    case 4:  // 40–49 баллов
    case 3:  // 30–39 баллов (оценка FX: 35–59 баллов)
        if (score >= 35) {
            cout << "Оценка: FX — Неудовлетворительно " << endl;
        }
        else {
            // Если 30–34 балла — это F
            cout << "Оценка: F — Неудовлетворительно " << endl;
        }
        break;
    case 2:  // 20–29 баллов
    case 1:  // 10–19 баллов
    case 0:  // 0–9 баллов
        cout << "Оценка: F — Неудовлетворительно " << endl;
        break;
    }
    return 0; 
}